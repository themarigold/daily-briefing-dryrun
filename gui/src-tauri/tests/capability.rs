//! What the webview may ask the Rust shell to do — asserted THROUGH Tauri's permission layer, not
//! against a second copy of the rules — and what each granted command then DOES, asserted by
//! driving all ten ENGINE commands through real IPC against a fake sidecar (the shell, B5 and B6
//! commands are driven here too, and in `shell.rs`, `briefing_files.rs` and `config_save.rs`).
//!
//! ## What replaced what (B1 → T8), because this file used to say the opposite
//!
//! B1 shipped this as `capability_allowlist.rs`: fifteen tests over a `shell:allow-execute` scope
//! with twenty-five enumerated argv entries. That design was measured to have a **first-match
//! ceiling** — `tauri-plugin-shell` resolves a sidecar's scope key from its `externalBin` path and
//! looks it up with `iter().find(|s| s.name == command_name)`, so every entry necessarily shared
//! one name and only the FIRST was ever consulted. Exactly one argv (`status --json`) was
//! reachable, and a foreign argv was not refused but *normalised* into that one.
//!
//! T8 lifts the ceiling by removing the mechanism rather than widening it. **The webview has no
//! shell access at all**: `tauri-plugin-shell` is not a dependency of this crate in any table, is
//! not registered on the builder, and the capability grants no `shell:*` permission. Every engine
//! invocation is constructed Rust-side from a typed operation enum and exposed as one
//! `#[tauri::command]` per operation. So the tests that pinned the ceiling — entry ordering, the
//! argv normalisation canary, the per-flag validator mirrors — have no subject any more and are
//! **deleted**, not weakened. The measurement itself is kept, as history, in
//! `capabilities/README.md`; the operand validators are tested at their new home in
//! `tests/engine_client.rs`, where they are Rust functions rather than regex strings in a config
//! file.
//!
//! What survives from B1 is the pair of structural pins that were never about the shell at all:
//! **exactly one capability file, and no inline or platform-merged capabilities.** The logic is
//! identical; the assertion messages were reworded for the new design.
//!
//! ## What is asserted here, and what is not
//!
//!   * **Behavioural, through real `get_ipc_response` calls against an app built from
//!     `tauri::generate_context!()` and `daily_briefing_gui_lib::handler()` — the same context and
//!     the same handler `run()` ships.** Refusals: the shell plugin's commands (absent, so refused);
//!     an engine command name that is not granted. Admissions: **all ten commands, each driven
//!     with VALID arguments into a fake sidecar managed as the app's `Engine` state**, asserting
//!     the response is `Ok` AND the argv the fake received is the literal the engine's grammar
//!     expects. Every command body is therefore EXECUTED, not merely reached — a mutation that
//!     replaces `engine_schedule_install`'s body with a constant `Ok` fails
//!     `every_command_body_runs_through_real_ipc_against_a_fake_sidecar` because the fake is never
//!     spawned.
//!   * **Never against the real sidecar.** The mock app manages `Engine(Ok(with_program(<fake>)))`
//!     — `EngineClient::bundled()` is not called anywhere in this file, so no test here can reach
//!     `~/Library/LaunchAgents` or the developer's state directory through `schedule install`.
//!   * **Structural:** the grant list, the command list in `build.rs`, `engine::COMMANDS` and the
//!     committed `permissions/autogenerated/` file set all agree; no permission mentions the
//!     shell; `capabilities/` holds one file and nothing is declared inline or in a platform
//!     sibling.
//!
//! ⚠ AND A TYPO IN THE CAPABILITY IS A COMPILE ERROR, not a silent ungrant. `tauri-build`'s
//! `validate_capabilities` refuses a permission identifier no manifest defines, so
//! `"allow-engine-statuss"` fails `cargo build` rather than shipping a command nobody can reach.
//! That is why the structural test can be about the SET rather than about each name's existence.
//!
//! ⚠ THE MUTATING COMMANDS TAKE THE PROCESS-GLOBAL IN-FLIGHT GUARD, and `cargo test` runs this
//! binary's tests on parallel threads. Every IPC call that reaches a spawn therefore lives in ONE
//! test, sequentially; the other tests are chosen to fail before any spawn (an ACL refusal, an
//! operand refusal, an argument-deserialisation failure), so they cannot contend for the guard.

