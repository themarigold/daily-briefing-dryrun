/// The grant list, `build.rs`'s command list, `lib.rs`'s `generate_handler!` list and
/// `engine::COMMANDS` are FOUR spellings of one thing, and each is load-bearing in a different
/// place: the capability decides what the webview may call, `build.rs` decides which permissions
/// exist AT ALL (and, by declaring an app manifest, whether app commands are ACL-checked in the
/// first place), `generate_handler!` decides which commands the runtime will dispatch, and
/// `COMMANDS` is the name every other test reads. A command missing from any one of the four is
/// unreachable, ungranted, ungated or undispatched, and none of those failures is visible from the
/// other three.
///
/// ⚠ `generate_handler!` WAS THE ONE SPELLING NOTHING PINNED, and it was measured: a ninth
/// `#[tauri::command] engine_ninth` registered in `generate_handler!` ALONE — absent from
/// `COMMANDS`, from `build.rs` and from the capability — left `cargo test --locked` at 44 passed /
/// 0 failed. Nothing objected. The runtime fails closed (the ACL answers `engine_ninth not
