        // measured). The crate sits in `[dependencies]`, so `tauri-build` collected its ACL
        // manifest (`gen/schemas/acl-manifests.json` carries an `opener` entry) and the ACL
        // refuses the ungranted command one layer BEFORE the missing registration could answer.
