/// ⚠ `tauri-plugin-opener` IS A DEPENDENCY AND THE WEBVIEW CANNOT REACH IT — the same property, and
/// the same reasoning, as `tauri-plugin-shell`'s absence.
///
/// The crate is in `[dependencies]` because `src/access.rs` calls its FREE functions (`open_url`,
/// `reveal_item_in_dir`) Rust-side. `tauri_plugin_opener::init()` is **never called**, so the
/// plugin's commands do not exist at runtime at all — which is stronger than granting them nothing
/// — and the capability names no `opener:` permission. A grant here would hand the webview a
/// general "open this URL" and a general "reveal this path", which is exactly the surface T17's
/// four commands exist to avoid.
#[test]
fn the_webview_cannot_reach_the_opener_plugin() {
    let f = fixture();
    let w = main_webview(&f.app);

    for (cmd, body) in [
        (
            "plugin:opener|open_url",
            serde_json::json!({ "url": "https://example.com" }),
        ),
        (
            "plugin:opener|open_path",
            serde_json::json!({ "path": "/etc/passwd" }),
        ),
        (
            "plugin:opener|reveal_item_in_dir",
            serde_json::json!({ "path": "/etc/passwd" }),
        ),
    ] {
        let o = attempt(&w, cmd, body);
        assert_eq!(
            o.verdict,
            Verdict::Refused,
            "{cmd} was NOT refused: {}. The opener plugin must stay unregistered and ungranted — \
             `src/access.rs` uses its free functions, which need neither.",
            o.message
        );
        // ⚠ THE REFUSAL'S SHAPE IS THE ACL'S, NOT THE SHELL'S `Plugin not found` (round 1,
        // measured). The crate sits in `[dependencies]`, so `tauri-build` collected its ACL
        // manifest (`gen/schemas/acl-manifests.json` carries an `opener` entry) and the ACL
        // refuses the ungranted command one layer BEFORE the missing registration could answer.
        // Four docs describe this shape (Cargo.toml, `src/access.rs`'s header,
        // `capabilities/README.md`, gui-seam dev 81); this assertion is what keeps them honest.
        // (Round 2: this list said "three" and omitted the README, and the README's copy was
        // exactly the one that kept the pre-correction claim — enumerate ALL of them.)
        assert!(
            o.message
                .contains("not allowed. Permissions associated with this command"),
            "{cmd}'s refusal changed shape — it is no longer the ACL's \"Permissions associated \
             with this command\". Update the four docs that describe it (Cargo.toml, \
             src/access.rs header, capabilities/README.md, gui-seam deviation 81): {}",
            o.message
        );
    }
    assert!(
        f.opener.urls().is_empty() && f.opener.reveals().is_empty(),
        "a refused plugin call still reached the sink"
    );

    // And the capability names no `opener:` permission at all.
    let raw = include_str!("../capabilities/default.json");
    let capability: serde_json::Value =
        serde_json::from_str(raw).expect("capabilities/default.json is valid JSON");
    for permission in capability["permissions"]
        .as_array()
        .expect("a permissions array")
    {
        let identifier = permission
            .as_str()
            .or_else(|| permission["identifier"].as_str())
            .unwrap_or_default();
        assert!(
            !identifier.starts_with("opener:"),
            "the capability grants {identifier:?}. T17's whole premise is that the webview picks a \
             PANE and a ROOT from closed enums; an opener permission gives it arbitrary URLs and \
             paths instead."
        );
    }
}

