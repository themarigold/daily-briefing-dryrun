/// The grant list, `build.rs`'s command list, `lib.rs`'s `generate_handler!` list and
/// `engine::COMMANDS` are FOUR spellings of one thing, and each is load-bearing in a different
/// place: the capability decides what the webview may call, `build.rs` decides which permissions
/// exist AT ALL (and, by declaring an app manifest, whether app commands are ACL-checked in the
/// first place), `generate_handler!` decides which commands the runtime will dispatch, and
/// `COMMANDS` is the name every other test reads. A command missing from any one of the four is
/// unreachable, ungranted, ungated or undispatched, and none of those failures is visible from the
/// other three.
///
/// ⚠ `generate_handler!` WAS THE ONE SPELLING NOTHING PINNED, and it was measured: a ninth
/// `#[tauri::command] engine_ninth` registered in `generate_handler!` ALONE — absent from
/// `COMMANDS`, from `build.rs` and from the capability — left `cargo test --locked` at 44 passed /
/// 0 failed. Nothing objected. The runtime fails closed (the ACL answers `engine_ninth not
/// allowed. Command not found`), so this is a hygiene pin rather than a hole: an undeclared
/// command is dead weight that reads as a feature, and the opposite direction — a command DROPPED
/// from `generate_handler!` while its grant, permission and `COMMANDS` entry survive — is a
/// silently unreachable command with a full paper trail saying otherwise.
#[test]
fn the_capability_grants_exactly_the_app_commands() {
    let capability: serde_json::Value =
        serde_json::from_str(include_str!("../capabilities/default.json"))
            .expect("capabilities/default.json is valid JSON");
    // ⚠ BOTH GRANT FORMS. A capability entry is either a string or an object with an
    // `identifier` (optionally scoped), and Tauri ENFORCES the object form: MEASURED,
    // `{ "identifier": "core:window:allow-close" }` was admitted at runtime while the previous
    // `filter_map(as_str)` here skipped it and every assertion below stayed green. An entry with
    // neither shape is a failure, not something to skip.
    let permissions: Vec<String> = capability["permissions"]
        .as_array()
        .expect("a permissions array")
        .iter()
        .map(|p| {
            p.as_str()
                .or_else(|| p["identifier"].as_str())
                .unwrap_or_else(|| {
                    panic!(
                        "capabilities/default.json has a permission entry that is neither a \
                         string nor an object with a string `identifier`: {p}"
                    )
                })
                .to_string()
        })
        .collect();

    // ⚠ A LITERAL ALLOWLIST OF THE NON-COMMAND GRANTS, NOT A PREFIX FILTER. The tempting rule is
    // "ignore anything with a colon in it", which would silently admit `shell:allow-execute` (the
    // grant T8 exists to have removed) or `core:tray:allow-new`. The core grants this webview
    // needs are enumerated here, and they are exactly the two `listen()`/unlisten use —
    // `core:default` is NOT among them: it hands the webview the live tray, menu and resources
    // surfaces and `plugin:event|emit` (`the_webview_cannot_reach_the_tray_menu_resources_or_emit`
    // refuses them behaviourally). `window-state`'s commands are unused (its persistence is
    // Rust-side) and `single-instance` has none.
    //
    // B7 added T19's three: `tauri-plugin-autostart`'s WHOLE shipped allow-set (its
    // `permissions/default.toml` is exactly `allow-enable`, `allow-disable`, `allow-is-enabled` —
    // read, not assumed). Phase E M5b KEEPS ONE: `allow-is-enabled`, because the Settings toggle
    // reflects REAL state via `is_enabled()`; `allow-enable`/`allow-disable` are gone, replaced by
    // the app command `autostart_set_enabled`, which brands the plist (`src/autostart.rs`).
    // `notification:*` is deliberately NOT here: that plugin is registered for the RUST side and
    // its commands stay refused (`the_webview_cannot_reach_the_notification_plugin`).
    // Each grant carries ITS OWN reason (round 1: one shared message claimed `listen()` breaks
    // for all five, which was true of two and nonsense for the autostart three).
    const NON_COMMAND_GRANTS_WITH_WHY: &[(&str, &str)] = &[
        (
            "core:event:allow-listen",
            "without it `listen()` is refused and the webview never hears `state:changed`",
        ),
        (
            "core:event:allow-unlisten",
            "without it the function `listen()` returns cannot unsubscribe",
        ),
        (
            "autostart:allow-is-enabled",
            "the Settings toggle reflects REAL plist state per render through this plugin command",
        ),
    ];
    const NON_COMMAND_GRANTS: &[&str] = &[
        "core:event:allow-listen",
        "core:event:allow-unlisten",
        "autostart:allow-is-enabled",
    ];
    for (grant, why) in NON_COMMAND_GRANTS_WITH_WHY {
        assert_eq!(
            permissions.iter().filter(|p| p == grant).count(),
            1,
            "{grant} must be granted exactly once — {why}"
        );
    }
    assert_eq!(
        NON_COMMAND_GRANTS_WITH_WHY
            .iter()
            .map(|(g, _)| *g)
            .collect::<Vec<_>>(),
        NON_COMMAND_GRANTS.to_vec(),
        "the reasons table and the allowlist drifted apart"
    );
    let mut granted: Vec<String> = permissions
        .iter()
        .filter(|p| !NON_COMMAND_GRANTS.contains(&p.as_str()))
        .cloned()
        .collect();
    granted.sort();
    for permission in &permissions {
        assert!(
            NON_COMMAND_GRANTS.contains(&permission.as_str()) || permission.starts_with("allow-"),
            "the capability grants {permission:?}, which is neither one of this app's own commands \
             nor a member of the enumerated NON_COMMAND_GRANTS list. Add it there deliberately, \
             with a reason, or remove it."
        );
    }

    // `tauri-utils` slugifies `_` to `-` when it autogenerates `allow-$command`
    // (`acl/build.rs:290`).
    let mut expected: Vec<String> = all_commands()
        .iter()
        .map(|c| format!("allow-{}", c.replace('_', "-")))
        .collect();
    expected.sort();

    assert_eq!(
        granted, expected,
        "the capability's grants and `all_commands()` disagree. Every app command must be \
         granted exactly once, and nothing else may be granted: an extra grant is a permission for \
         a command that does not exist (which `tauri-build` would have refused) and a missing one \
         is a command the webview cannot call."
    );

    // ⚠ AND THE WHOLE SET AS A LITERAL. The comparison above is derived from `all_commands()`, so a
    // command added to a module's `COMMANDS`, `build.rs`, the handler AND the capability together
    // would pass it silently. This list is what a reviewer sees change: B5 added five, B6 adds
    // `allow-engine-schedule-verify` (T20 — MUTATING: it makes the live scheduler run the engine)
    // plus T17's four, B7 adds T18's two app commands (no path, no post) plus T19's three
    // autostart plugin grants — `enable` and `disable` WRITE/REMOVE a login-item plist in
    // `~/Library/LaunchAgents`, which is why they are the one webview surface whose REAL effect
    // the suite never executes (VM-gated; the ACL admission is asserted against an app without
    // the plugin registered) — B8 adds `allow-config-create` (the wizard's exclusive
    // first-config write) plus the three `allow-cli-shim-*` grants (dev 63; the real
    // `/usr/local/bin` leg VM-gated behind the sink), 28 → 32 — and B25 adds the two
    // `allow-uninstall-*` grants (T25: preview reads, execute removes the app's OWN pieces and,
    // only behind its one explicit consent boolean, the engine-state list pinned against
    // scripts/uninstall.sh; the real autostart-disable leg VM-gated behind T19's sink), 32 → 34 — and
    // Phase E (E12) adds `allow-engine-update-check` (`update --check --json`, "Check now": NOT
    // mutating, no operand, the request is the engine's), 34 → 35 — and Phase E M5b swaps T19's
    // plugin `autostart:allow-enable` / `allow-disable` for the app's `allow-autostart-set-enabled`
    // (one boolean: ON = the plugin's enable PLUS the macOS branding, OFF = its disable) and
    // `allow-autostart-wizard-default` (reads the record and the real state for the wizard's
    // pre-tick), 35 → 35.
    const EXPECTED_GRANTS: &[&str] = &[
        "core:event:allow-listen",
        "core:event:allow-unlisten",
        "allow-engine-status",
        "allow-engine-doctor",
        "allow-engine-run",
        "allow-engine-run-to-file",
        "allow-engine-config-validate",
        "allow-engine-schedule-install",
        "allow-engine-schedule-uninstall",
        "allow-engine-schedule-status",
        "allow-engine-schedule-verify",
        "allow-engine-update-check",
        "allow-state-snapshot",
        "allow-open-today",
        "allow-app-quit",
        "allow-read-latest-briefing",
        "allow-read-archived-briefing",
        "allow-config-read",
        "allow-config-save",
        "allow-config-offer-notify-auto",
        "allow-config-create",
        "allow-access-snapshot",
        "allow-access-probe",
        "allow-access-reveal-engine",
        "allow-access-open-settings",
        "allow-notify-status",
        "allow-notify-set-enabled",
        "allow-cli-shim-status",
        "allow-cli-shim-install",
        "allow-cli-shim-remove",
        "allow-uninstall-preview",
        "allow-uninstall-execute",
        "allow-autostart-set-enabled",
        "allow-autostart-wizard-default",
        "autostart:allow-is-enabled",
    ];
    assert_eq!(
        permissions, EXPECTED_GRANTS,
        "capabilities/default.json is not exactly the enumerated thirty-five grants, in order"
    );

    // The third spelling. `build.rs` cannot import this crate, so its list is a copy — which is
    // tolerable only because this assertion exists.
    let build_rs = include_str!("../build.rs");
    for command in all_commands() {
        assert!(
            build_rs.contains(&format!("\"{command}\"")),
            "build.rs does not declare {command:?}. Without it there is no `allow-{}` permission \
             for the capability to reference, and `cargo build` fails — but if the capability's \
             reference were removed at the same time, the command would silently become \
             unreachable instead.",
            command.replace('_', "-")
        );
    }
    // ⚠ COUNTED BY QUOTED ENTRY, NOT BY `engine_` PREFIX. B3 counted `    "engine_` occurrences,
    // which worked while every command started with that word; T11's three do not, and a prefix
    // count would simply stop seeing them. The count is what catches an EXTRA entry, which the
    // containment check above cannot.
    let declared = build_rs
        .lines()
        .filter(|line| line.trim_start().starts_with('"') && line.trim_end().ends_with("\","))
        .count();
    assert_eq!(
        declared,
        all_commands().len(),
        "build.rs declares {declared} commands and the crate declares {} — the containment check \
         above cannot see an EXTRA one, and an extra autogenerated permission nobody grants is a \
         command that is defined, ungranted and invisible.",
        all_commands().len()
    );

    // The fourth spelling: the `generate_handler!` list itself. PARSED, not counted — a count
    // agrees with a list that has the right length and the wrong names.
    let lib_rs = include_str!("../src/lib.rs");
    const OPEN: &str = "tauri::generate_handler![";
    let start = lib_rs
        .find(OPEN)
        .expect("lib.rs registers an invoke handler with `tauri::generate_handler![`")
        + OPEN.len();
    let body = &lib_rs[start..][..lib_rs[start..]
        .find(']')
        .expect("the generate_handler! list is closed with `]`")];
    let registered: Vec<&str> = body
        .split(',')
        .map(str::trim)
        .filter(|entry| !entry.is_empty())
        .collect();
    // prove-it 3b: a parse that silently matched nothing would make every assertion below vacuous.
    assert!(
        !registered.is_empty(),
        "nothing was parsed out of lib.rs's `generate_handler!` list. The parse — not the code — \
         is what broke; fix it rather than deleting the assertions it feeds. Body was: {body:?}"
    );
    // ⚠ AN ENUMERATED MODULE ALLOWLIST, NOT A WILDCARD. B3 required every entry to start with
    // `engine::` — the only module that existed. T11 adds `shell::`, and the loosening that would
    // have been easy here is "strip everything before `::`", which would let a command from ANY
    // module into the handler without anyone noticing. The two modules are named, and a third one
    // has to be added here on purpose.
    const COMMAND_MODULES: &[&str] = &[
        "engine::",
        "shell::",
        "briefing_files::",
        "config_save::",
        "access::",
        "notifications::",
        "cli_shim::",
        "uninstall::",
        "autostart::",
    ];
    let mut registered_names: Vec<&str> = Vec::new();
    for entry in &registered {
        let name = COMMAND_MODULES
            .iter()
            .find_map(|m| entry.strip_prefix(m))
            .unwrap_or_else(|| {
                panic!(
                    "lib.rs registers {entry:?}, which is not from one of {COMMAND_MODULES:?}. \
                     Every invoke handler entry must come from a module whose `COMMANDS` list this \
                     test compares against, because that list is what the capability, `build.rs` \
                     and `permissions/autogenerated/` are all pinned to."
                )
            });
        registered_names.push(name);
    }
    assert_eq!(
        registered_names,
        all_commands(),
        "lib.rs's `generate_handler!` list and `all_commands()` disagree. Each module's `COMMANDS` \
         doc says it is \"in the order `lib.rs` registers them\", so this is compared as a \
         SEQUENCE: a command registered but not declared is undeclared dead weight the ACL will \
         refuse at runtime, and one declared but not registered is granted, permitted, documented \
         and unreachable."
    );
    let unique: BTreeSet<&str> = registered_names.iter().copied().collect();
    assert_eq!(
        unique.len(),
        registered_names.len(),
        "lib.rs registers a command twice: {registered_names:?}"
    );
}

/// The committed `permissions/autogenerated/` file set is exactly one `<command>.toml` per engine
/// command, each defining its own `allow-`/`deny-` pair.
///
/// ⚠ WHY A RENAME NEEDS THIS. `tauri-utils` writes the autogenerated files with `write_if_changed`
/// and NEVER deletes one (`acl/build.rs:307-309`), so renaming a command leaves `<old>.toml` in
/// place defining an `allow-<old>` permission that nothing grants and nothing references. Nothing
/// else objects: the build succeeds, the capability validates, and the other structural test reads
/// `COMMANDS` and the grants rather than the directory. This is the one test that reads the
/// directory.
#[test]
fn autogenerated_permissions_match_the_command_set() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("permissions")
        .join("autogenerated");
    let mut on_disk: Vec<String> = std::fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("{} is readable: {e}", dir.display()))
        .map(|entry| entry.expect("a readable directory entry").path())
        .filter(|p| p.extension().and_then(|e| e.to_str()) == Some("toml"))
        .map(|p| {
            p.file_stem()
                .expect("a .toml file has a stem")
                .to_string_lossy()
                .into_owned()
        })
        .collect();
    on_disk.sort();

    let mut expected: Vec<String> = all_commands().iter().map(|c| c.to_string()).collect();
    expected.sort();

    assert_eq!(
        on_disk, expected,
        "permissions/autogenerated/ and engine::COMMANDS disagree. An extra file is a stale \
         permission from a renamed or deleted command (tauri-utils never removes one); a missing \
         file means the build has not regenerated since the command was added — run `cargo build` \
         and commit the result."
    );

    for command in all_commands() {
        let slug = command.replace('_', "-");
        let text = std::fs::read_to_string(dir.join(format!("{command}.toml")))
            .unwrap_or_else(|e| panic!("{command}.toml is readable: {e}"));
        for needle in [
            format!("identifier = \"allow-{slug}\""),
            format!("identifier = \"deny-{slug}\""),
            format!("commands.allow = [\"{command}\"]"),
            format!("commands.deny = [\"{command}\"]"),
        ] {
            assert!(
                text.contains(&needle),
                "{command}.toml does not contain {needle:?} — it is not the autogenerated file \
                 for {command}"
            );
        }
    }
}

/// ⚠ STILL LOAD-BEARING AFTER THE SHELL SCOPE IS GONE, and for a reason that has nothing to do
/// with the shell.
///
/// `include_str!` reads ONE FILE. The resolved ACL does not: `tauri-build` globs
/// `./capabilities/**/*` and `parse_capabilities` collects the results into a
/// `BTreeMap<String, Capability>` keyed by capability IDENTIFIER (`tauri-utils`
/// `acl/build.rs:204-243`). A second file declaring `aaa-extra` is merged with `default` and ITS
/// grants apply too — so `the_capability_grants_exactly_the_app_commands` above could stay
/// perfectly green while the shipped ACL granted `shell:allow-execute` and every engine command
/// with it.
///
/// Inline capabilities are the same hole by another door: `app.security.capabilities` in
/// `tauri.conf.json` is a second source of entries, and `acl/mod.rs:358` resolves capabilities as
/// `if config.app.security.capabilities.is_empty() { from_files } else { …inline… }` — a non-empty
/// list REPLACES the files entirely.
///
/// ⚠ AND `tauri.conf.json` IS NOT THE ONLY CONFIG FILE. `include_str!` below reads that one name;
/// the builder reads that name and then JSON-Merge-Patches a PLATFORM SIBLING over it. Hence the
/// third assertion — see `platform_config_siblings_on_disk`.
///
/// REFINED BY B23 (docs/gui-seam.md §15b, deviation 156; hardened in round 1). This assertion
/// used to require ZERO platform siblings; T23's per-platform bundle targets legitimately live in
/// three of them. The GUARDED PROPERTY is unchanged and now stated directly: no config file the
/// builder merges may reach ANYTHING outside `bundle.*` — a merged `app.security.capabilities`
/// REPLACES the capability files outright. Bundle-only bounds the ACL blast radius; it does NOT
/// make a sibling harmless — `frameworks`, `files`, `infoPlist`, `exceptionDomain` are bundle
/// keys with runtime consequences (embedded dylibs, arbitrary in-bundle file placement,
/// Info.plist merges, an ATS cleartext exception) — so the key walk is paired with SET-EQUALITY:
/// the discovered sibling set must equal EXACTLY the three recorded files, via the discovery walk
/// SHARED with `tests/packaging.rs`'s targets-authority pin (`tests/common/mod.rs` — one
/// enumeration, two enforcing suites). A fourth sibling is refused outright rather than admitted
/// key-bounded, and a broken walk fails equality in both suites instead of walking nothing
/// (round 1 measured both holes: a neutered suffix predicate and a hostile
/// `tauri.ios.conf.json` were green under the walk-only version). Every discovered sibling must
/// still parse as PLAIN JSON (a `.json5` or `.toml` sibling that serde_json cannot read fails
/// LOUDLY here rather than dodging the key walk) and carry top-level keys within
/// {"$schema", "bundle"}.
#[test]
fn exactly_one_capability_file_exists_and_nothing_is_declared_inline() {
    assert_eq!(
        capability_files_on_disk(),
        vec!["default.json".to_string()],
        "capabilities/ must hold EXACTLY ONE capability file. Tauri merges every file it finds by \
         capability identifier, so a second one can grant permissions this suite never reads while \
         every assertion about default.json stays green."
    );

    let config: serde_json::Value = serde_json::from_str(include_str!("../tauri.conf.json"))
        .expect("tauri.conf.json is valid JSON");
    let inline = config["app"]["security"]["capabilities"]
        .as_array()
        .map(Vec::len)
        .unwrap_or(0);
    assert_eq!(
        inline, 0,
        "tauri.conf.json declares {inline} INLINE capability entries — same displacement risk as a \
         second capability file, and invisible to every other test here."
    );

    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let siblings = platform_config_siblings_on_disk();
    assert_eq!(
        siblings,
        [
            "tauri.linux.conf.json",
            "tauri.macos.conf.json",
            "tauri.windows.conf.json"
        ],
        "the platform-config sibling set drifted off the three files dev 156 records. A \
         FOURTH sibling — even a bundle-only one; tauri.ios.conf.json is a real merge target \
         (tauri-utils config/parse.rs:58) — is refused by SET-EQUALITY, not admitted by the \
         key walk below: nothing else on this machine ever reads such a file, so the walk \
         would be its only reader. And an EMPTY discovery means the walk itself broke — \
         equality fails loudly instead of walking nothing."
    );
    for name in siblings {
        let text = std::fs::read_to_string(root.join(&name)).unwrap_or_else(|e| {
            panic!("platform config sibling {name} exists but is unreadable: {e}")
        });
        let parsed: serde_json::Value = serde_json::from_str(&text).unwrap_or_else(|e| {
            panic!(
                "platform config sibling {name} is not PLAIN JSON ({e}) — the builder would \
                 still merge it over tauri.conf.json before the ACL is resolved, but this test \
                 cannot inspect its keys; only bundle-only .conf.json siblings are permitted \
                 (§15b dev 156)"
            )
        });
        let stray: Vec<&String> = parsed
            .as_object()
            .unwrap_or_else(|| panic!("platform config sibling {name} is not a JSON object"))
            .keys()
            .filter(|k| k.as_str() != "$schema" && k.as_str() != "bundle")
            .collect();
        assert!(
            stray.is_empty(),
            "platform config sibling {name} reaches beyond bundle.*: {stray:?}. The builder \
             JSON-Merge-Patches this file over tauri.conf.json BEFORE the ACL is resolved, and a \
             merged non-empty app.security.capabilities REPLACES the capability files outright — \
             so a key outside {{$schema, bundle}} can grant anything while capabilities/ still \
             holds exactly default.json and the include_str!-ed tauri.conf.json still declares \
             nothing inline. Platform siblings are BUNDLE-ONLY (§15b dev 156); keep it that way."
        );
    }
}

/// Every file under `capabilities/` that `tauri_build` would PARSE as a capability, as paths
/// relative to that directory, sorted.
///
/// Mirrors `parse_capabilities("./capabilities/**/*")` exactly: recursive over EVERY subdirectory,
/// filtered to the capability file extensions (`tauri-utils` `acl/build.rs:42-48`), then dropping
/// files the way the real filter drops them (`:217`). Read from DISK at run time on purpose —
/// `include_str!` can only ever see the file it names, which is the entire hole this closes.
/// Non-capability files (this directory's `README.md`) are ignored, because Tauri ignores them.
///
/// ⚠ THE `schemas/` EXCLUSION IS PER-FILE, NOT PER-SUBTREE, and an earlier revision of this walk
/// got that backwards. `acl/build.rs:217` is
/// `.filter(|p| p.parent().unwrap().file_name().unwrap() != CAPABILITIES_SCHEMA_FOLDER_NAME)` — it
/// tests the file's IMMEDIATE parent directory, so `capabilities/schemas/sub/aaa-extra.json`
/// (parent `sub`) is parsed and merged like any other capability. Descend into `schemas/`; skip
/// only its direct children.
fn capability_files_on_disk() -> Vec<String> {
    fn walk(dir: &Path, root: &Path, out: &mut Vec<String>) {
        let entries =
            std::fs::read_dir(dir).unwrap_or_else(|e| panic!("{} is readable: {e}", dir.display()));
        for entry in entries {
            let path = entry.expect("a readable directory entry").path();
            if path.is_dir() {
                walk(&path, root, out);
                continue;
            }
            if !matches!(
                path.extension().and_then(|e| e.to_str()),
                Some("json" | "json5" | "toml")
            ) {
                continue;
            }
            // `acl/build.rs:217`, per-file and on the immediate parent only.
            let in_a_schemas_dir = path
                .parent()
                .and_then(Path::file_name)
                .and_then(|n| n.to_str())
                == Some("schemas");
            if in_a_schemas_dir {
                continue;
            }
            out.push(
                path.strip_prefix(root)
                    .expect("walked from root")
                    .display()
                    .to_string(),
            );
        }
    }

    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("capabilities");
    let mut out = Vec::new();
    walk(&root, &root, &mut out);
    out.sort();
    out
}

