/// The mock app. NO shell plugin is registered — none is a dependency of this crate in any table
/// — so `plugin:shell|*` is refused because the plugin is absent, and that is the property T8
/// ships: there is nothing to grant.
fn app_managing(
    engine: Engine,
    access: AccessState,
    notify: NotifyState,
    autostart: AutostartState,
) -> App<MockRuntime> {
    // ⚠ `EngineSnapshots` IS MANAGED HERE TOO, AND IT HAS TO BE. `state_snapshot` resolves it
    // through `State<'_, Arc<EngineSnapshots>>`, and Tauri's `State` extractor PANICS when nothing
    // of that type is managed — so a mock app without it would fail the command with a panic
    // inside the IPC handler rather than with the refusal or the result the test is about. It is
    // built from the SAME `Result` as the engine state, exactly as `lib.rs::run()` does.
    let snapshots = Arc::new(EngineSnapshots::new(engine.0.clone()));
    mock_builder()
        .manage(engine)
        .manage(snapshots)
        // The per-app quit latch, as `lib.rs::run()` manages it — fresh, so "not shown yet".
        .manage(ShellState::default())
        // T15's save lock, for the same `State` reason. ⚠ WITH A CANDIDATE DIRECTORY: the default
        // resolves `app_data_dir()`, which on MockRuntime is the developer's real one. No test in
        // this file gets as far as validating a candidate (the fake's `status` names no config),
        // so the directory is never created; `tests/config_save.rs` drives the whole pipeline.
        .manage(ConfigSaver::with_candidate_dir(
            std::env::temp_dir().join("daily-briefing-t8-capability-candidates-unused"),
        ))
        // T17's state, for the same `State` reason — and pointed at a scratch `HOME` by every
        // caller (see `access_state`), because `access_probe` READS the directory it names.
        .manage(access)
        // T18's state, ALWAYS with a recording sink and a scratch store: managed without a sink,
        // the shipped plugin post would be reachable from a test app; the store default is
        // MockRuntime's REAL `app_data_dir()` (the ConfigSaver/AccessState trap again).
        //
        // ⚠ Neither T19 plugin is registered here. `plugin:notification|*` must be REFUSED (no
        // grant), and `plugin:autostart|enable`'s REAL body writes `~/Library/LaunchAgents` — the
        // ACL admission of the autostart grants is asserted against this plugin-less app, where a
        // command that got past the ACL finds no plugin and nothing real can execute.
        .manage(notify)
        // B8's CLI-shim state, for the same `State` reason — and pointed at a SCRATCH directory
        // with a recording sink: the default is the REAL `SystemShim` over `/usr/local/bin`
        // (the ConfigSaver/AccessState trap, a third time). The commands read the engine before
        // any sink call, and this fixture's run-shaped fake fails that read — but the state must
        // still never be one whose sink could write outside a sandbox.
        .manage(
            CliShimState::default()
                .with_sink(Arc::new(RecordingShimSink))
                .with_dir(std::env::temp_dir().join("daily-briefing-t8-capability-shim-unused")),
        )
        // T19's autostart state, ALWAYS with a recording sink and a scratch store (every caller
        // passes one): B25's `uninstall_execute` and M5b's two autostart commands resolve it
        // (`autostart::enabled_now` / `enable_now` / `disable_now`), and managing it WITHOUT a
        // sink would send that resolution to the real plugin manager — which is not registered
        // here, and whose real `enable()`/`disable()` WRITE/REMOVE a `~/Library/LaunchAgents`
        // plist; without a store, `autostart_set_enabled` would write its record into
        // MockRuntime's REAL `app_data_dir()` (the ConfigSaver/AccessState trap again).
        .manage(autostart)
        // B25's uninstall state, for the same `State` reason — with a sink that answers "nothing
        // there" and REMOVES NOTHING, and scratch app directories and home: the default is the real
        // filesystem over the real `app_data_dir()`/`app_config_dir()` (the ConfigSaver/
        // AccessState trap, a fourth time), and `uninstall_execute` DELETES files.
        .manage(
            UninstallState::default()
                .with_fs(Arc::new(InertUninstallFs))
                .with_app_data_dir(
                    std::env::temp_dir().join("daily-briefing-t8-capability-uninstall-unused"),
                )
                .with_app_config_dir(
                    std::env::temp_dir().join("daily-briefing-t8-capability-uninstall-unused"),
                )
                .with_home_dir(
                    std::env::temp_dir().join("daily-briefing-t8-capability-uninstall-unused"),
                ),
        )
        .invoke_handler(daily_briefing_gui_lib::handler())
        .build(tauri::generate_context!())
        .expect("mock app should build from the shipped tauri.conf.json + capabilities")
}

