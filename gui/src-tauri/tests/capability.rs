/// The capability is scoped to `"windows": ["main"]`, so the label is load-bearing: a webview under
/// any other label gets nothing at all, and every negative assertion below would then pass for the
/// wrong reason.
fn main_webview(app: &App<MockRuntime>) -> WebviewWindow<MockRuntime> {
    WebviewWindowBuilder::new(app, "main", Default::default())
        .build()
        .expect("main webview")
}

/// Verbatim from Tauri core's ACL denial (`ipc/authority.rs`, `webview/mod.rs`). Each one means
/// the permission layer said no. `Plugin not found` is the one a `plugin:shell|…` call produces —
/// that crate is in no dependency table, so no ACL manifest was collected for it. A crate that IS
/// in `[dependencies]` (opener, window-state) gets the ACL's `Permissions associated with this
/// command` instead, registered or not: the collected manifest lets the ACL answer before the
/// missing registration would (measured, rounds 1–2). Either is a refusal.
const REFUSAL_MARKERS: &[&str] = &[
    "not allowed. Permissions associated with this command",
    "not allowed. Command not found",
    "not allowed. Plugin not found",
    "not allowed by ACL",
    "not allowed on window",
    "explicitly denied on origin",
];

#[derive(Debug, PartialEq, Eq)]
enum Verdict {
    /// The permission layer let the call through — to our own code, which is where any error
    /// came from.
    Admitted,
    /// The permission layer refused it.
    Refused,
}

struct Outcome {
    verdict: Verdict,
    /// The error's text, or empty on success.
    message: String,
    /// The response body on success.
    body: Option<InvokeResponseBody>,
}

fn request(cmd: &str, body: serde_json::Value) -> InvokeRequest {
    InvokeRequest {
        cmd: cmd.into(),
        callback: CallbackFn(0),
        error: CallbackFn(1),
        url: "tauri://localhost".parse().unwrap(),
        body: InvokeBody::Json(body),
        headers: Default::default(),
        invoke_key: INVOKE_KEY.to_string(),
    }
}

/// Drive one IPC message and classify what came back.
///
/// ⚠ NOTHING HERE PASSES AN ENVIRONMENT, and that is the difference from B1's namesake. The shell
/// plugin took a frontend-supplied `env` and forwarded it to the child, so B1's harness could — and
/// had to — sandbox the engine from the webview side. The engine commands take no environment at
/// all: the sandbox is the fake sidecar the app STATE points at, chosen by the test, not by the
/// message.
fn attempt(w: &WebviewWindow<MockRuntime>, cmd: &str, body: serde_json::Value) -> Outcome {
    match get_ipc_response(w, request(cmd, body)) {
        Ok(body) => Outcome {
            verdict: Verdict::Admitted,
            message: String::new(),
            body: Some(body),
        },
        Err(e) => {
            let msg = e
                .as_str()
                .map(str::to_string)
                .unwrap_or_else(|| e.to_string());
            let refused = REFUSAL_MARKERS.iter().any(|m| msg.contains(m));
            Outcome {
                verdict: if refused {
                    Verdict::Refused
                } else {
                    Verdict::Admitted
                },
                message: msg,
                body: None,
            }
        }
    }
}

/* ── the classifier, interrogated before anything is concluded from it ────────────────────────── */

/// `prove-it` step 3b: a check that can pass while the claim is false is worse than no check.
/// `attempt`'s fallback branch is `Admitted`, so if refusal detection were broken every negative
/// assertion in this file would still be written the same way and every one would be vacuous. This
/// pins both branches against known-good inputs.
#[test]
fn the_classifier_can_tell_the_two_verdicts_apart() {
    let f = fixture();
    let w = main_webview(&f.app);

    // Granted, and refused by OUR validator rather than by the ACL — so the message must NOT look
    // like a refusal.
    let admitted = attempt(
        &w,
        "engine_config_validate",
        serde_json::json!({ "file": "not/absolute" }),
    );
    assert_eq!(
        admitted.verdict,
        Verdict::Admitted,
        "a granted command was reported as ACL-refused: {}",
        admitted.message
    );
    assert!(
        admitted.message.contains("not an absolute path"),
        "expected the operand refusal from src/engine.rs, got: {}",
        admitted.message
    );

    // Not granted, and not even defined.
    let refused = attempt(&w, "engine_init", serde_json::json!({}));
    assert_eq!(
        refused.verdict,
        Verdict::Refused,
        "an unknown command should be refused, got: {}",
        refused.message
    );
}

/* ── NEGATIVE: the shell is gone ──────────────────────────────────────────────────────────────── */

/// The headline property of T8, and what it proves: **the plugin is absent, so the call is
/// refused.** `tauri-plugin-shell` is in no dependency table of this crate — not `[dependencies]`,
/// not `[dev-dependencies]` — so there is no plugin to register on the mock app and no ACL manifest
/// for it; the refusal is `Plugin not found`. (A dev-dependency used to be kept so the plugin could
/// be registered here and the refusal would come from the capability instead. MEASURED: it never
/// did — `tauri-build` collects ACL manifests from `[dependencies]` only, so registering a
/// dev-dependency plugin adds no manifest and the refusal was `Plugin not found` either way. The
/// dependency bought nothing and is gone.)
///
/// The assertion accepts either refusal text, so it holds the day someone adds the plugin back
/// WITHOUT a grant — and fails the day the capability grants `shell:*` again.
///
/// ⚠ Seen red by GRANTING it: add `"shell:allow-execute"` to `capabilities/default.json` on a
/// disposable copy and `cargo build` refuses the capability (no manifest defines it). The
/// capability is never edited to make a test pass.
#[test]
fn the_webview_cannot_reach_the_shell_plugin() {
    let f = fixture();
    let w = main_webview(&f.app);

    for (cmd, body) in [
        (
            "plugin:shell|execute",
            serde_json::json!({
                "program": "binaries/daily-briefing",
                "args": ["status", "--json"],
                "options": { "sidecar": true }
            }),
        ),
        (
            "plugin:shell|spawn",
            serde_json::json!({
                "program": "binaries/daily-briefing",
                "args": ["run", "--force"],
                "options": { "sidecar": true }
            }),
        ),
        (
            "plugin:shell|open",
            serde_json::json!({ "path": "https://example.invalid" }),
        ),
    ] {
        let o = attempt(&w, cmd, body);
        assert_eq!(
            o.verdict,
            Verdict::Refused,
            "{cmd} was NOT refused — the webview can still reach the shell plugin: {}",
            o.message
        );
    }
}

