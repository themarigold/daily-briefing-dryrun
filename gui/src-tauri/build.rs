//! Build-time ACL generation.
//!
//! ⚠ AN APP ACL MANIFEST IS WHAT MAKES THE CAPABILITY MEAN ANYTHING, and that is not obvious.
//! Tauri 2 ACL-checks an application's own commands **only when the app declared an ACL manifest**
//! — `webview/mod.rs:1823-1826`: `if (plugin_command.is_some() || has_app_acl_manifest || !is_local)
//! && request.cmd != FETCH_CHANNEL_DATA_COMMAND && invoke.acl.is_none() { reject }` (the
//! `FETCH_CHANNEL_DATA_COMMAND` exemption is Tauri's own channel plumbing, not an app command).
//! Without a manifest, `has_app_acl_manifest` is false, every `#[tauri::command]` in this crate is
//! reachable from the local webview whatever `capabilities/default.json` says, and the capability
//! would be documentation.
//!
//! ⚠ THE MANIFEST HAS TWO SOURCES, AND EITHER ONE ALONE KEEPS THE GATE UP — measured on a
//! disposable copy, all four combinations:
//!
//!   * **`.commands(…)` below.** `tauri-build` autogenerates an `allow-<command>` /
//!     `deny-<command>` permission pair per name into `permissions/autogenerated/` (`tauri-build`
//!     `acl.rs:274-289`; the `_`→`-` slugify is `tauri-utils` `acl/build.rs:290`).
//!   * **The committed `permissions/` directory.** With the call removed, `app_manifest_permissions`
//!     falls through to its default `permissions/**/*` glob (`tauri-build` `acl.rs:300-328`) and
//!     finds the same files. `has_app_manifest` is `default_permission.is_some() ||
//!     !permission_sets.is_empty() || !permissions.is_empty()` (`acl.rs:408-410`), so either source
//!     makes it true.
//!
//!   | `.commands(…)` | `permissions/` | result |
//!   | --- | --- | --- |
//!   | kept | deleted | regenerated at build; capability tests green |
//!   | removed | kept | glob finds the committed files; capability tests green |
//!   | removed | removed (grants kept) | `failed to run custom build command` — the capability references permissions no manifest defines |
//!   | removed | removed (grants removed too) | builds; the engine commands are UNGATED; the structural tests go red |
//!
//! So the gate is pinned by `commands(…)` ∨ the committed directory, and only removing both
//! (and then editing the capability to match) reaches the ungated state. The directory is
//! committed because it is a REGENERABLE, TRACKED SNAPSHOT that makes the manifest reviewable in a
//! diff — not because it is the sole gate. `tauri-utils` writes it with `write_if_changed` and
//! never deletes a file (`acl/build.rs:307-309`), so a RENAMED command leaves `<old>.toml` behind
//! defining a permission nothing grants; `tests/capability.rs`'s
//! `autogenerated_permissions_match_the_command_set` is what catches that, and
//! `the_capability_grants_exactly_the_app_commands` pins this list, the capability's grants,
//! `commands::all_commands()` and `lib.rs`'s `generate_handler!` against each other.
//!
//! Everything else `tauri_build::build()` did still happens: `tauri.conf.json` and
//! `capabilities/*.json` are parsed and the RESOLVED ACL is baked into the binary, so a malformed
//! capability is a compile error here rather than a runtime surprise.

fn main() {
    let attributes = tauri_build::Attributes::new()
        .app_manifest(tauri_build::AppManifest::new().commands(daily_briefing_gui_commands()));
    if let Err(error) = tauri_build::try_build(attributes) {
        panic!("failed to run tauri-build: {error:#}");
    }
}

/// The command list, duplicated from every module's `COMMANDS` (in `commands.rs`'s `all_commands`
